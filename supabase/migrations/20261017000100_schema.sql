-- =====================================================================
-- Kantine – Schema (Phase 1)
--
-- Grundprinzipien:
--  * Alle Tabellen haben Row Level Security (siehe nächste Migration).
--  * Clients (Handy/Tablet) schreiben NIE direkt in Tabellen, sondern
--    nur über die Funktionen aus der Migration "funktionen".
--  * Das Guthaben steht in personen.guthaben und wird nur von den
--    Funktionen geändert. Jede Änderung erzeugt eine Zeile in
--    guthaben_buchungen (Historie, wird nach 30 Tagen gelöscht).
-- =====================================================================

create schema if not exists private;

-- ---------------------------------------------------------------------
-- Personen: Wachabteilung (feste Kollegen) UND Gäste/Azubis/Notarzt/...
-- Ein Konto (Handy-Login) ist optional und hängt über profile an der Person.
-- ---------------------------------------------------------------------
create table public.personen (
    id              uuid primary key default gen_random_uuid(),
    kategorie       text not null check (kategorie in
                      ('wachabteilung','bdienst','fahrer_bdienst','notarzt','azubi','gaeste')),
    anzeigename     text not null check (char_length(btrim(anzeigename)) between 1 and 60),
    guthaben        numeric(10,2) not null default 0,   -- negativ = Schulden
    aktiv           boolean not null default true,      -- false = "gelöscht" (Gast) bzw. ausgeschieden
    erstellt_am     timestamptz not null default now(),
    deaktiviert_am  timestamptz
);

-- Namen in der Wachabteilung dürfen nicht doppelt vorkommen (wie in der alten App)
create unique index personen_wache_name_uq
    on public.personen (lower(btrim(anzeigename)))
    where kategorie = 'wachabteilung' and aktiv;

create index personen_kategorie_idx on public.personen (kategorie) where aktiv;

-- ---------------------------------------------------------------------
-- Profile: verbindet einen Supabase-Auth-Benutzer mit Rolle und Person
-- ---------------------------------------------------------------------
create table public.profile (
    id           uuid primary key references auth.users(id) on delete cascade,
    benutzername text not null unique
                   check (benutzername ~ '^[a-z0-9][a-z0-9._-]{1,29}$'),
    rolle        text not null check (rolle in ('admin','kueche','mitglied')),
    person_id    uuid unique references public.personen(id) on delete restrict,
    aktiv        boolean not null default true,
    erstellt_am  timestamptz not null default now(),
    constraint profile_mitglied_braucht_person check (rolle <> 'mitglied' or person_id is not null),
    constraint profile_kueche_ohne_person      check (rolle <> 'kueche'   or person_id is null)
);

-- ---------------------------------------------------------------------
-- Produkte (die 6 Kategorien sind fest, es gibt keine Kategorienverwaltung)
-- ---------------------------------------------------------------------
create table public.produkt_kategorien (
    id        smallint primary key,
    name      text not null,
    sortierung smallint not null
);

create table public.produkte (
    id                   bigint generated by default as identity primary key,
    kategorie_id         smallint not null references public.produkt_kategorien(id),
    name                 text not null check (char_length(btrim(name)) between 1 and 60),
    preis                numeric(8,2) not null check (preis >= 0),
    typ                  text not null default 'sonstiges' check (char_length(typ) between 1 and 60),
    zaehlt_einkaufsliste boolean not null default false,
    ist_abendessen       boolean generated always as
                           (typ in ('abendessen_normal','abendessen_vegetarisch')) stored,
    aktiv                boolean not null default true,   -- false = "gelöscht" (Historie bleibt lesbar)
    erstellt_am          timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Tagesabschlüsse (leichter Snapshot: Einkaufsliste + Zahlen, KEINE Salden)
-- ---------------------------------------------------------------------
create table public.tagesabschluesse (
    id               uuid primary key default gen_random_uuid(),
    erstellt_am      timestamptz not null default now(),
    durchgefuehrt_von uuid,
    snapshot         jsonb not null default '{}'::jsonb
);

-- ---------------------------------------------------------------------
-- Bestellungen + Positionen (Preis wird zum Bestellzeitpunkt gespeichert)
-- ---------------------------------------------------------------------
create table public.bestellungen (
    id                uuid primary key default gen_random_uuid(),
    person_id         uuid not null references public.personen(id),
    erfasst_von       uuid,                                   -- auth.users.id (Handy-Konto oder Küchen-Konto)
    quelle            text not null check (quelle in ('handy','tablet')),
    client_request_id uuid not null unique,                   -- verhindert Doppelbestellungen bei Wiederholung
    summe             numeric(10,2) not null default 0,
    tagesabschluss_id uuid references public.tagesabschluesse(id),
    erstellt_am       timestamptz not null default now()
);
create index bestellungen_person_idx on public.bestellungen (person_id, erstellt_am desc);
create index bestellungen_offen_idx  on public.bestellungen (id) where tagesabschluss_id is null;
create index bestellungen_zeit_idx   on public.bestellungen (erstellt_am);

create table public.bestellpositionen (
    id                   bigint generated always as identity primary key,
    bestellung_id        uuid not null references public.bestellungen(id) on delete cascade,
    produkt_id           bigint references public.produkte(id) on delete set null,
    bezeichnung          text not null,                        -- Snapshot des Produktnamens
    einzelpreis          numeric(8,2) not null check (einzelpreis >= 0),  -- Snapshot (Abendessen = 0)
    menge                integer not null check (menge between 1 and 99),
    zaehlt_einkaufsliste boolean not null default false,       -- Snapshot
    ist_abendessen       boolean not null default false,       -- Snapshot
    ist_individuell      boolean not null default false
);
create index bestellpositionen_bestellung_idx on public.bestellpositionen (bestellung_id);

-- ---------------------------------------------------------------------
-- Guthaben-Buchungen (Historie; Saldo nach der Buchung wird mitgespeichert)
-- ---------------------------------------------------------------------
create table public.guthaben_buchungen (
    id            bigint generated always as identity primary key,
    person_id     uuid not null references public.personen(id),
    art           text not null check (art in ('bestellung','aufladung','abendessen','uebernahme')),
    betrag        numeric(10,2) not null,                      -- signiert: Abbuchung negativ
    saldo_danach  numeric(10,2) not null,
    bestellung_id uuid references public.bestellungen(id) on delete set null,
    bezeichnung   text,
    erstellt_von  uuid,
    erstellt_am   timestamptz not null default now()
);
create index guthaben_buchungen_person_idx on public.guthaben_buchungen (person_id, erstellt_am desc);
create index guthaben_buchungen_zeit_idx   on public.guthaben_buchungen (erstellt_am);

-- ---------------------------------------------------------------------
-- Abendessen-Liste (wird in der Küche abgerechnet)
-- ---------------------------------------------------------------------
create table public.abendessen_eintraege (
    id          uuid primary key default gen_random_uuid(),
    person_id   uuid not null references public.personen(id),
    vegetarisch boolean not null default false,
    status      text not null default 'offen'
                  check (status in ('offen','abgerechnet','entfernt','verworfen')),
    preis       numeric(8,2),
    erstellt_am timestamptz not null default now(),
    erledigt_am timestamptz
);
-- Pro Person darf es nur EINEN offenen Eintrag geben (wie in der alten App)
create unique index abendessen_offen_person_uq
    on public.abendessen_eintraege (person_id) where status = 'offen';
create index abendessen_zeit_idx on public.abendessen_eintraege (erstellt_am);

